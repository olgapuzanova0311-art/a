def plural(n, one, few, many):
    n = abs(n) % 100
    if 11 <= n <= 19:
        return many
    n %= 10
    return one if n == 1 else few if 2 <= n <= 4 else many


def left_text(seconds):
    h = max(1, round(seconds / 3600))
    if h >= 36:
        return "ещё почти двое суток"
    if h >= 20:
        return "ещё сутки"
    return f"ещё {h} {plural(h, 'час', 'часа', 'часов')}"


