def guess_dept(*texts):
    """Отдел для нового агента по его имени и роли (когда нанимает оркестратор или бот, отдел не указан)."""
    t = ' '.join(texts).lower()
    for dept, words in KEYWORDS:
        if any(w in t for w in words):
            return dept
    return None
